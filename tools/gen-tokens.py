#!/usr/bin/env python3
"""Generate Qt/QML + CSS artefacts from design/tokens/xos.tokens.json.

The token file is the single source of truth.  Everything generated here is
committed, and CI fails when a generated file drifts from the source.

Usage:
    tools/gen-tokens.py            # write generated files
    tools/gen-tokens.py --check    # exit 1 if something is out of date
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "design" / "tokens" / "xos.tokens.json"
QML_OUT = ROOT / "shell" / "qml" / "PlasmaX" / "Theme.qml"
CSS_OUT = ROOT / "design" / "generated" / "tokens.css"

BANNER = "// AUTO-GENERATED by tools/gen-tokens.py — do not edit by hand.\n"


def qml_value(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return f"{value}"
    if isinstance(value, list):
        return "[" + ", ".join(qml_value(v) for v in value) + "]"
    return json.dumps(value)


def qml_theme(tokens: dict) -> str:
    out: list[str] = [BANNER]
    out.append("pragma Singleton")
    out.append("import QtQuick")
    out.append("")
    out.append("QtObject {")
    out.append(f'    readonly property string version: {json.dumps(tokens["meta"]["version"])}')
    out.append("")
    out.append("    // Runtime theme mode — the shell flips this at runtime.")
    default_mode = tokens["meta"].get("defaultMode", "dark")
    out.append(f'    property string mode: {json.dumps(default_mode)}')
    out.append('    readonly property bool lightMode: mode === "light"')
    out.append("    readonly property QtObject c: lightMode ? light : dark")
    out.append("    readonly property QtObject g: lightMode ? glassLight : glassDark")

    def emit(section: str, prefix: str, src: dict) -> None:
        out.append("")
        out.append(f"    // ── {section} " + "─" * max(1, 52 - len(section)))
        if prefix:
            # Nested QtObject so QML can read Theme.r.xs / Theme.s.sm / …
            out.append(f"    readonly property QtObject {prefix}: QtObject {{")
            inner = "        "
            for key, value in src.items():
                out.append(f"{inner}readonly property var {key}: {qml_value(value)}")
            out.append("    }")
        else:
            for key, value in src.items():
                out.append(f"    readonly property var {key}: {qml_value(value)}")

    c = tokens["color"]
    for mode in ("dark", "light"):
        out.append("")
        out.append(f"    // ── color.{mode} " + "─" * 36)
        out.append(f"    readonly property QtObject {mode}: QtObject {{")
        for key, value in c[mode].items():
            out.append(f"        readonly property color {key}: {json.dumps(value)}")
        out.append("    }")

    out.append("")
    out.append("    // ── palette shortcuts (Theme.accent → c.accent) " + "─" * 8)
    for key in c["dark"]:
        out.append(f"    readonly property color {key}: c.{key}")

    for mode in ("dark", "light"):
        out.append("")
        out.append(f"    // ── glass.{mode} " + "─" * 36)
        out.append(f"    readonly property QtObject glass{mode.capitalize()}: QtObject {{")
        for key, value in tokens["glass"][mode].items():
            prop = "color" if isinstance(value, str) and value.startswith("#") else "real"
            out.append(f"        readonly property {prop} {key}: {qml_value(value)}")
        out.append("    }")

    emit("radius", "r", tokens["radius"])
    emit("space", "s", tokens["space"])

    out.append("")
    out.append("    // ── type " + "─" * 50)
    out.append("    readonly property QtObject type: QtObject {")
    for key, value in tokens["type"].items():
        prop = "var" if isinstance(value, list) else ("string" if isinstance(value, str) else "real")
        out.append(f"        readonly property {prop} {key}: {qml_value(value)}")
    out.append("    }")

    motion = tokens["motion"]
    out.append("")
    out.append("    // ── motion " + "─" * 48)
    out.append("    readonly property QtObject motion: QtObject {")
    for key, value in motion["durations"].items():
        out.append(f"        readonly property int {key}: {value}")
    for key, value in motion["easings"].items():
        out.append(f"        readonly property var ease{key.capitalize()}: {qml_value(value)}")
    out.append("        readonly property QtObject spring: QtObject {")
    for key, value in motion["spring"].items():
        out.append(f"            readonly property real {key}: {value}")
    out.append("        }")
    out.append(f"        readonly property real reducedMotionScale: {motion['reducedMotionScale']}")
    out.append("    }")

    emit("layout", "", tokens["layout"])
    emit("elevation", "shadow", tokens["elevation"])
    out.append("}")
    out.append("")
    return "\n".join(out)


def css_vars(tokens: dict) -> str:
    lines = ["/* AUTO-GENERATED by tools/gen-tokens.py — do not edit by hand. */", ":root {"]
    for mode in ("dark", "light"):
        for key, value in tokens["color"][mode].items():
            lines.append(f"  --xos-{mode}-{key}: {value};")
        for key, value in tokens["glass"][mode].items():
            lines.append(f"  --xos-glass-{mode}-{key}: {value};")
    for section in ("radius", "space", "elevation"):
        for key, value in tokens[section].items():
            lines.append(f"  --xos-{section}-{key}: {value}px;")
    for key, value in tokens["type"].items():
        if isinstance(value, (int, float)):
            lines.append(f"  --xos-type-{key}: {value}px;")
    for key, value in tokens["motion"]["durations"].items():
        lines.append(f"  --xos-motion-{key}: {value}ms;")
        lines.append(f"  --xos-motion-{key}s: {value / 1000:.3f}s;")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="verify generated files are current")
    args = parser.parse_args()

    tokens = json.loads(TOKENS.read_text(encoding="utf-8"))
    produced = {QML_OUT: qml_theme(tokens), CSS_OUT: css_vars(tokens)}

    stale = []
    for path, content in produced.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            stale.append(path)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")

    if args.check and stale:
        print("Generated files are out of date:", file=sys.stderr)
        for path in stale:
            print(f"  - {path.relative_to(ROOT)}", file=sys.stderr)
        print("Run `make tokens` and commit the result.", file=sys.stderr)
        return 1

    if not args.check:
        for path in produced:
            print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
